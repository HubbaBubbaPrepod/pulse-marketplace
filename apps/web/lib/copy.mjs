export function pathFor(lang, path = '') {
  return `/${lang}/${path ? `${path}/` : ''}`;
}
const pluralRules = { ru: new Intl.PluralRules('ru'), en: new Intl.PluralRules('en') };
export function moduleCount(count, lang) {
  const form = pluralRules[lang].select(count);
  const word =
    lang === 'ru'
      ? { one: 'модуль', few: 'модуля', many: 'модулей', other: 'модуля' }[form]
      : form === 'one'
        ? 'module'
        : 'modules';
  return `${count} ${word}`;
}
